/// Write the icons (if changed) and register the directory with the icon theme.
pub fn install(display: &gtk::gdk::Display) {
    let base = std::env::var_os("XDG_CACHE_HOME")
        .map(PathBuf::from)
        .filter(|p| p.is_absolute())
        .or_else(|| std::env::var_os("HOME").map(|h| PathBuf::from(h).join(".cache")))
        .unwrap_or_else(std::env::temp_dir)
        .join("hwpedit/icons");
    let dir = base.join("hicolor/scalable/actions");
    if std::fs::create_dir_all(&dir).is_err() {
        return;
    }
    for (name, svg) in icons() {
        let p = dir.join(format!("hwpedit-{name}-symbolic.svg"));
        if std::fs::read_to_string(&p).ok().as_deref() != Some(svg.as_str()) {
            let _ = std::fs::write(&p, svg);
        }
    }
    gtk::IconTheme::for_display(display).add_search_path(&base);
}

/// Icon name for one of ours, or `sys:<name>` for `<name>-symbolic` from the icon
/// theme (falling back to a plain document icon when the theme lacks it).
pub fn name(n: &str) -> String {
    if let Some(sys) = n.strip_prefix("sys:") {
        let full = format!("{sys}-symbolic");
        let have = gtk::gdk::Display::default()
            .is_some_and(|d| gtk::IconTheme::for_display(&d).has_icon(&full));
        return if have { full } else { name("doc-generic") };
    }
    format!("hwpedit-{n}-symbolic")
}

