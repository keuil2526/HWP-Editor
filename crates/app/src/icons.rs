//! The editor's own symbolic icons (16x16, fill-only so GTK recolours them for
//! light and dark themes). Common icon themes lack many of these, which left
//! blank buttons. They are written to the user cache at startup and added to the
//! icon theme search path; names are `hwpedit-<name>-symbolic`.

use std::path::PathBuf;

/// Filled shapes in a 16x16 box.
enum S {
    /// x, y, w, h
    R(f32, f32, f32, f32),
    /// frame: x, y, w, h, thickness
    O(f32, f32, f32, f32, f32),
    /// SVG path data (even-odd fill)
    P(&'static str),
}
use S::*;

fn svg(shapes: &[S]) -> String {
    let mut body = String::new();
    for s in shapes {
        let d = match s {
            R(x, y, w, h) => format!("M{x} {y}h{w}v{h}h{}z", -w),
            O(x, y, w, h, t) => format!(
                "M{x} {y}h{w}v{h}h{}zM{} {}v{}h{}v{}z",
                -w,
                x + t,
                y + t,
                h - 2.0 * t,
                w - 2.0 * t,
                -(h - 2.0 * t)
            ),
            P(d) => (*d).to_owned(),
        };
        body.push_str(&format!(
            "<path fill=\"#2e3436\" fill-rule=\"evenodd\" d=\"{d}\"/>"
        ));
    }
    format!("<svg xmlns=\"http://www.w3.org/2000/svg\" width=\"16\" height=\"16\" viewBox=\"0 0 16 16\">{body}</svg>")
}

